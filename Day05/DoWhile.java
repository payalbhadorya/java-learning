package Day05;

public class DoWhile {
    public static void main(String[] args) {
        int i = 1; // 1 to 5
        do{
            System.out.println(i);
            i++;
        }while(i<=5);

        int i1 = 10; // print just 6 q ki yaha humne 5 se 1 bada no. likhne bala tha..
        do{
            System.out.println(i1);
            i++;
        }while(i1<=5);

    }
    
}
