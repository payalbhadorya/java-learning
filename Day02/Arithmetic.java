package Day02;

public class Arithmetic {
    public static void main(String[] args) {
        int a = 48;
        int b = 84;
        int c = 186;

        System.out.println(a + b + c);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b); //modulus 

        int sum = a + b + c;
        System.out.println("Sum:" + sum);
    }
    
}
